function optionBlocks(explanation) {
  const section = explanation.split("【選項詳解】")[1]?.split("【核心考點】")[0] || "";
  const matches = [...section.matchAll(/(?:^|\n)\s*-\s*([A-D])\.\s*/g)];
  return matches.map((match, index) => {
    const end = index + 1 < matches.length ? matches[index + 1].index : section.length;
    return [match[1], section.slice(match.index + match[0].length, end).trim()];
  });
}

function repeatedSegments(explanation) {
  const seen = new Map();
  for (const [label, block] of optionBlocks(explanation)) {
    for (const part of block.split(/[。；;!?！？\n]+/)) {
      const compact = part.replace(/\s+/g, "");
      if (compact.length < 36) continue;
      if (!seen.has(compact)) seen.set(compact, new Set());
      seen.get(compact).add(label);
    }
  }
  return [...seen.entries()]
    .filter(([, labels]) => labels.size >= 3)
    .map(([segment, labels]) => ({ segment, labels: [...labels].sort() }));
}

function validateUpdateFilePayload(payload, sourceQuestions) {
  const issues = [];
  if (payload.source_file !== sourceFile) issues.push(`source_file mismatch: ${payload.source_file}`);
  if (payload.dataset_id !== datasetId) issues.push(`dataset_id mismatch: ${payload.dataset_id}`);
  for (const item of payload.updates) {
    const allowedIssue = Object.keys(item).filter((key) => !allowedUpdateFields.has(key));
    if (allowedIssue.length) issues.push(`Q${item.question_number}: extra update fields ${allowedIssue.join(", ")}`);
    const original = sourceQuestions.get(item.question_id);
    if (!original) {
      issues.push(`Q${item.question_number}: missing original question`);
      continue;
    }
    if (original.question_number !== item.question_number) issues.push(`Q${item.question_number}: number mismatch`);
    if (item.question_number < payload.range.start || item.question_number > payload.range.end) {
      issues.push(`Q${item.question_number}: outside range`);
    }
    for (const heading of ["【題幹解析】", "【選項詳解】", "【核心考點】"]) {
      if (!item.explanation.includes(heading)) issues.push(`Q${item.question_number}: missing ${heading}`);
    }
    for (const label of ["A", "B", "C", "D"]) {
      if (!new RegExp(`- ${label}(?:\\.|[：:])`).test(item.explanation)) issues.push(`Q${item.question_number}: missing option ${label}`);
    }
    for (const phrase of bannedPhrases) {
      if (item.explanation.includes(phrase) || item.key_point.includes(phrase) || item.flashcard_summary.includes(phrase)) {
        issues.push(`Q${item.question_number}: banned phrase ${phrase}`);
      }
    }
    const repeated = repeatedSegments(item.explanation);
    if (repeated.length) issues.push(`Q${item.question_number}: repeated option segment ${repeated[0].segment}`);
  }
  return issues;
}

function stripImmutable(dataset) {
  const clone = JSON.parse(JSON.stringify(dataset));
  delete clone.updated_at;
  for (const question of clone.questions || []) {
    for (const field of [
      "explanation",
      "key_point",
      "flashcard_front",
      "flashcard_back",
      "flashcard_summary",
      "review_status",
      "explanation_model",
      "explanation_generated_at",
      "manual_review_notes",
    ]) {
      delete question[field];
    }
  }
  return clone;
}

function main() {
  const source = JSON.parse(fs.readFileSync(sourcePath, "utf8").replace(/^\uFEFF/, ""));
  if (source.id !== datasetId) throw new Error(`Unexpected dataset id: ${source.id}`);
  const sourceQuestions = new Map(source.questions.map((question) => [question.id, question]));
  if (updates.length !== 80) throw new Error(`Expected 80 updates, got ${updates.length}`);

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "before_merge_medicine-6.json"), `${JSON.stringify(source, null, 2)}\n`, "utf8");

  const updateFiles = [];
  const allIssues = [];
  for (let start = 1; start <= 80; start += 10) {
    const end = start + 9;
    const payload = {
      source_file: sourceFile,
      dataset_id: datasetId,
      range: { start, end },
      updates: updates.filter((item) => item.question_number >= start && item.question_number <= end),
    };
    const issues = validateUpdateFilePayload(payload, sourceQuestions);
    if (payload.updates.length !== 10) issues.push(`range ${start}-${end}: expected 10 updates`);
    allIssues.push(...issues.map((issue) => `q${String(start).padStart(3, "0")}-q${String(end).padStart(3, "0")}: ${issue}`));
    const fileName = `q${String(start).padStart(3, "0")}-q${String(end).padStart(3, "0")}.json`;
    const filePath = path.join(outDir, fileName);
    fs.writeFileSync(filePath, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
    updateFiles.push(filePath);
  }

  const validationFailurePath = path.join(outDir, "validation_failed.json");
  if (allIssues.length) {
    fs.writeFileSync(validationFailurePath, `${JSON.stringify({ issues: allIssues }, null, 2)}\n`, "utf8");
    throw new Error(`Update validation failed: ${allIssues.join("; ")}`);
  }
  if (fs.existsSync(validationFailurePath)) fs.unlinkSync(validationFailurePath);

  const beforeImmutable = stripImmutable(source);
  const byId = new Map(updates.map((item) => [item.question_id, item]));
  for (const question of source.questions) {
    const item = byId.get(question.id);
    if (!item) continue;
    for (const field of [
      "explanation",
      "key_point",
      "flashcard_front",
      "flashcard_back",
      "flashcard_summary",
      "review_status",
      "explanation_model",
      "explanation_generated_at",
      "manual_review_notes",
    ]) {
      question[field] = item[field];
    }
  }
  source.updated_at = generatedAt;
  const afterImmutable = stripImmutable(source);
  const immutableChanged = JSON.stringify(beforeImmutable) !== JSON.stringify(afterImmutable);
  if (immutableChanged) throw new Error("Immutable question fields changed during merge");

  fs.writeFileSync(sourcePath, `${JSON.stringify(source, null, 2)}\n`, "utf8");
  const report = {
    dataset_id: datasetId,
    source_file: sourceFile,
    generated_at: generatedAt,
    update_file_count: updateFiles.length,
    merged_question_count: updates.length,
    update_files: updateFiles.map((file) => path.relative(root, file).replace(/\\/g, "/")),
    immutable_changed: false,
    manual_review_questions: updates
      .filter((item) => item.manual_review_notes.length)
      .map((item) => ({ question_number: item.question_number, notes: item.manual_review_notes })),
  };
  fs.writeFileSync(path.join(outDir, "merge_report.json"), `${JSON.stringify(report, null, 2)}\n`, "utf8");
  console.log(JSON.stringify(report, null, 2));
}

main();
