const learningFields = [
  "explanation",
  "key_point",
  "flashcard_front",
  "flashcard_back",
  "flashcard_summary",
  "review_status",
  "explanation_model",
  "explanation_generated_at",
];

function immutableSnapshot(dataset) {
  return dataset.questions.map((question) => {
    const copy = { ...question };
    for (const field of learningFields) delete copy[field];
    return copy;
  });
}

function hash(value) {
  return crypto.createHash("sha256").update(JSON.stringify(value)).digest("hex");
}

function validateUpdates(dataset) {
  const byNumber = new Map(dataset.questions.map((question) => [question.question_number, question]));
  const seen = new Set();
  for (const update of updates) {
    if (seen.has(update.question_number)) throw new Error(`duplicate update ${update.question_number}`);
    seen.add(update.question_number);
    const source = byNumber.get(update.question_number);
    if (!source) throw new Error(`missing source question ${update.question_number}`);
    if (source.id !== update.question_id) throw new Error(`question id mismatch ${update.question_number}`);
    if (!update.explanation.includes("【題幹解析】") || !update.explanation.includes("【選項詳解】") || !update.explanation.includes("【核心考點】")) {
      throw new Error(`missing headings ${update.question_number}`);
    }
    for (const label of ["A", "B", "C", "D"]) {
      if (!update.explanation.includes(`- ${label}.`)) throw new Error(`missing option ${label} in ${update.question_number}`);
    }
  }
  if (updates.length !== 80) throw new Error(`expected 80 updates, got ${updates.length}`);
}

function writeBatchFiles() {
  fs.mkdirSync(outDir, { recursive: true });
  for (let start = 1; start <= 80; start += 10) {
    const end = start + 9;
    const batch = updates.filter((update) => update.question_number >= start && update.question_number <= end);
    const payload = {
      source_file: sourceFile,
      dataset_id: datasetId,
      range: { start, end },
      updates: batch,
    };
    const outPath = path.join(outDir, `q${String(start).padStart(3, "0")}-q${String(end).padStart(3, "0")}.json`);
    fs.writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
  }
}

function applyUpdates(dataset) {
  const byNumber = new Map(updates.map((update) => [update.question_number, update]));
  dataset.questions = dataset.questions.map((question) => {
    const update = byNumber.get(question.question_number);
    if (!update) return question;
    const next = { ...question };
    for (const field of learningFields) next[field] = update[field];
    return next;
  });
}

const dataset = JSON.parse(fs.readFileSync(sourcePath, "utf8").replace(/^\uFEFF/, ""));
if (dataset.id !== datasetId) throw new Error(`dataset id mismatch: ${dataset.id}`);
const beforeHash = hash(immutableSnapshot(dataset));
validateUpdates(dataset);
writeBatchFiles();
applyUpdates(dataset);
const afterHash = hash(immutableSnapshot(dataset));
if (beforeHash !== afterHash) throw new Error("immutable fields changed");
fs.writeFileSync(sourcePath, `${JSON.stringify(dataset, null, 2)}\n`, "utf8");

